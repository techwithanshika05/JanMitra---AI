"""
rag_pipeline.py

Main Retrieval-Augmented Generation (RAG) pipeline for JanMitra.

Pipeline:

User Question
    ->
QueryProcessor
    ->
Retriever
    ->
ContextBuilder
    ->
PromptBuilder
    ->
LLMClient
    ->
Groq API
    ->
Final Answer + Sources

This module orchestrates the complete query-time RAG workflow.

It does NOT handle:
- PDF extraction
- Text cleaning
- Chunk creation
- Document embedding
- ChromaDB ingestion

Those operations belong to the ingestion pipeline.
"""

